"""
matplotlib 绘图入门练习

本文件演示了 matplotlib 最基本的使用流程：
1. 用 numpy 生成一组 x 坐标数据；
2. 根据 x 计算出两条曲线的 y 值；
3. 创建两个独立的图形窗口（figure），分别绘制两条曲线；
4. 用 plt.show() 一次性弹出所有窗口进行展示。
"""

# ==================== 1. 导入库 ====================

# 导入 matplotlib 的绘图模块 pyplot，并给它起别名 plt。
# pyplot 提供了一套类似 MATLAB 的"命令式"绘图接口，
# 内部自动维护"当前图形窗口"和"当前坐标轴"，是 matplotlib 中最常用的入口。
import matplotlib.pyplot as plt

# 导入 numpy 数值计算库，并起别名 np。
# 这里用它生成坐标数据，并借助"向量化运算"对整组数据批量计算。
import numpy as np

# ==================== 2. 准备数据 ====================

# 生成 x 轴的坐标点：
# np.linspace(开始值, 结束值, 点的个数) 会在 [-3, 3] 这个闭区间内
# 均匀地取 50 个点（包含首尾两个端点），返回一个一维 numpy 数组。
# 例如 [-3.0, -2.878..., ..., 2.878..., 3.0]，相邻两点间距相等。
x = np.linspace(-3, 3, 50)

# 第一条曲线：y1 = 2x + 1，是一条斜率为 2、截距为 1 的直线。
# 因为 x 是 numpy 数组，2 * x + 1 会自动进行"向量化"运算：
# 即对数组中的每个元素都单独计算一次，返回一个长度相同的新数组。
# （如果是普通 Python 列表，2 * x 会变成把列表重复 2 遍，语义完全不同。）
y1 = 2 * x + 1

# 第二条曲线：y2 = x^2，是一条开口向上、顶点在原点的抛物线。
# x ** 2 同样是对数组逐元素求平方（numpy 的 ** 是逐元素幂运算），
# 而不是数学上的矩阵乘方。
y2 = x ** 2

# ==================== 3. 图形窗口 1 ====================

# 创建第 1 个图形窗口（figure）：
# num=1           给窗口编号为 1，之后再写 plt.figure(num=1) 会复用这个窗口而不是新建；
# figsize=(8,5)   设置窗口尺寸为宽 8 英寸、高 5 英寸（1 英寸 ≈ 2.54 厘米）。
# 执行完这行后，窗口 1 成为"当前窗口"，后面所有绘图命令都会默认画在它里面。
plt.figure(num=1, figsize=(8,5))

# 在窗口 1 中绘制第一条曲线：
# x, y1           分别给出横坐标、纵坐标的数据（两者长度必须一致）；
# color='gray'    线条颜色设为灰色（也可以用 '#808080' 这类十六进制色值）；
# linewidth=1.0   线条粗细 1.0 磅（pt），数值越大线条越粗；
# linestyle='--'  线型设为虚线。常用线型：'-'实线、'--'虚线、':'点线、'-.'点划线。
# plt.plot 返回一个包含 Line2D 对象的列表（这里没有接收，直接丢弃了）。
plt.plot(x, y1,color='gray',linewidth=1.0,linestyle='--')


# ==================== 4. 图形窗口 2 ====================

# 创建第 2 个图形窗口，编号为 2，尺寸 10 英寸 × 10 英寸。
# 注意：窗口之间完全独立——前面画在窗口 1 的灰色虚线不会出现在这张图上；
# 执行后"当前窗口"切换为窗口 2。
plt.figure(num=2, figsize=(10,10))

# 在窗口 2 中绘制第二条曲线：
# color='red'      红色；
# linewidth=1.0    粗细 1.0 磅；
# linestyle='-'    实线。
plt.plot(x, y2,color='red',linewidth=1.0,linestyle='-')

# 设置 x 轴的显示范围为 -1 到 2。
# 注意：这只是改变坐标轴的"观察窗口"（决定显示数据中的哪一段），
# 不会删除或修改任何数据；数据仍在，只是视口之外的点被裁剪不显示。
plt.xlim(-1,2)

# 设置 y 轴的显示范围为 -2 到 3，作用与 xlim 同理。
plt.ylim(-2,3)

# 设置 x 轴标签文字为 'x'，默认显示在 x 轴下方居中位置。
plt.xlabel('x')

# 设置 y 轴标签文字为 'y'，默认显示在 y 轴左侧居中位置。
plt.ylabel('y')

# 生成 x 轴刻度位置：
# 在闭区间 [-1, 2] 内均匀取 5 个点，得到 [-1.0, -0.25, 0.5, 1.25, 2.0]。
# 先保存到变量 new_ticks，下一步用它们自定义 x 轴刻度。
new_ticks = np.linspace(-1,2,5)

# 设置 x 轴的刻度位置：
# 只传一个参数时，刻度就画在这些数值位置，
# 刻度标签由 matplotlib 自动用对应数值生成（默认数字格式）。
plt.xticks(new_ticks)

# 设置 y 轴的刻度位置以及每个刻度对应的自定义标签：
# 第一个列表 [-2, -1.8, -1, 1.22, 3] 是刻度在数据坐标中的实际位置；
# 第二个列表是与之"一一对应"的标签文字——两个列表长度必须相同，顺序一一配对。
# 标签里使用了 LaTeX 数学公式语法：用一对 $ 包起来的内容会被渲染成公式。
# 字符串前的 r 表示"原始字符串"，让反斜杠 \ 保持字面意义，
# 不被 Python 当转义字符处理（否则 \a、\g 等可能报错或被吞掉）。
# 各标签渲染结果：
#   r'$really\ bad$'   ->  "really bad"（LaTeX 中 \ 后接空格表示普通空格）
#   r'$bad\ \alpha$'   ->  "bad α"（\alpha 渲染为希腊字母 α）
#   r'$normal$'        ->  普通文字 "normal"
#   r'$good$'          ->  普通文字 "good"
#   r'$really\ good$'  ->  "really good"
plt.yticks([-2,-1.8,-1,1.22,3],
           [r'$really\ bad$',r'$bad\ \alpha$',r'$normal$',r'$good$',r'$really\ good$'])

# ==================== 5. 面向对象方式改造坐标轴（"盒子框"变"十字轴"） ====================

# 获取当前图形窗口（这里是窗口 2）的坐标轴对象 Axes。
# gca = "get current axes"（获取当前坐标轴）。
# 前面用的 plt.xlim、plt.plot 等"面向过程"快捷函数，
# 内部实际也是在操作这个 Axes 对象；
# 拿到 ax 之后，就可以用"面向对象"的方式做更精细的控制。
ax = plt.gca()

# 一个坐标轴四周有四条"脊线"（spines）：
# top（上）、bottom（下）、left（左）、right（右），
# 它们共同构成坐标轴最外层的矩形边框。
# 下面的操作把默认的"盒子形"边框改成数学课本里常见的"十字形"坐标轴。

# 隐藏右边框：把 right 脊线的颜色设为 'none'（透明，即不显示）。
ax.spines['right'].set_color('none')

# 隐藏上边框：把 top 脊线的颜色设为 'none'。
ax.spines['top'].set_color('none')

# 让 x 轴刻度只显示在 bottom（下方）脊线上。
# 默认 top 和 bottom 两边都画刻度，这里只保留下方。
ax.xaxis.set_ticks_position('bottom')

# 让 y 轴刻度只显示在 left（左侧）脊线上。
# 默认 left 和 right 两边都画刻度，这里只保留左侧。
ax.yaxis.set_ticks_position('left')

# 把 bottom（下方）脊线整体移动到 y=0 的位置：
# ('data', 0) 中 'data' 表示使用"数据坐标系"（即坐标轴上的实际数值），
# 0 表示目标位置。效果：x 轴经过 y=0，成为穿过原点的水平轴。
ax.spines['bottom'].set_position(('data',0))

# 把 left（左侧）脊线整体移动到 x=0 的位置，同理使用数据坐标。
# 效果：y 轴经过 x=0，成为穿过原点的竖直轴。
# 两步合起来，x 轴与 y 轴就在原点 (0, 0) 处交叉，形成十字坐标轴。
ax.spines['left'].set_position(('data',0))

# ==================== 5.5 在曲线上标注特殊点（散点 + 垂足线 + 文字注解） ====================
# 下面 5 行仍画在窗口 2 的十字坐标系里，演示如何把曲线上某个特殊点"圈出来"并加文字说明。

# 设定要标注点的横坐标：x0 = 1。
# 这个点在抛物线 y = x^2 上，其坐标应为 (1, 1^2) = (1, 1)。
x0 = 1

# 按曲线方程 y = x^2 计算该点的纵坐标：y0 = 1 ** 2 = 1.0。
# 用公式计算而不是直接手写 1，可以保证该点精确落在曲线上（改 x0 时自动跟着变）。
y0 = x0 ** 2

# 用散点图把 (1, 1) 这个点标出来：
# x0, y0        点的坐标（这里是两个标量，也可以传数组画多个点）；
# color='red'   点设为红色；
# s=50          点的大小为 50（面积单位，数值越大点越大）。
# scatter 与 plot 的区别：scatter 只画离散的点、不连线，且能单独控制每个点的
# 颜色和大小（s 参数是 scatter 特有的，plot 没有）。
plt.scatter(x0,y0,color='red',s=50)

# 从点 (1, 1) 向 x 轴画一条"垂足线"（垂直线段），即起点 (x0, y0)、终点 (x0, 0)：
# [x0,x0]  横坐标列表：两个值都是 x0=1，所以这条线段是竖直的；
# [y0,0]   纵坐标列表：从 y0=1 一直落到 0（正好落在 x 轴上）；
# 'k--'    简写线型：k 表示 black（黑色），-- 表示虚线；
# lw=2     线宽 2 磅（lw 是 linewidth 的缩写）。
# 这条虚线直观地把曲线上的点和它在 x 轴上的投影连接起来，方便读数。
plt.plot([x0,x0],[y0,0],'k--',lw=2)

# 添加文字标注（annotate），在点 (1, 1) 附近显示该点满足的方程 x^2 = 1.00：
# r'$x^2=%.2f$' % y0
#   先用 % 格式化把 y0=1.0 填入字符串，得到 r'$x^2=1.00$'；
#   %.2f 表示按浮点数保留两位小数；外层 $...$ 表示用 LaTeX 渲染数学公式
#   （x^2 会显示为上标 x²），前缀 r 表示原始字符串、反斜杠不被转义。
# xy=(x0,y0)      箭头最终指向的目标点，坐标 (1, 1)；
# xycoords='data'  xy 使用"数据坐标系"（即坐标轴上的实际数值）；
# xytext=(+30,-30) 文字锚点相对目标点的偏移量：(+30, -30)，单位由 textcoords 决定；
# textcoords='offset points'  偏移量以"点"（pt）为单位：
#                 +30 表示向右偏移 30 磅，-30 表示向下偏移 30 磅，
#                 因此文字会出现在点的右下方；
# fontsize=16     文字字号 16 磅；
# arrowprops=dict(...)  箭头样式（以字典形式传入）：
#     arrowstyle='->'               箭头本身是简单的实线箭头；
#     connectionstyle='arc3,rad=.2' 箭头连线带弧度（rad=0.2 控制弯曲程度），
#                                   让箭头绕一个小弧线指向目标点，避免与曲线重叠。
plt.annotate(r'$x^2=%.2f$' % y0, xy=(x0,y0), xycoords='data', xytext=(+30,-30), textcoords='offset points', fontsize=16, arrowprops=dict(arrowstyle='->', connectionstyle='arc3,rad=.2'))
# 在图上添加一段"自由文字"（text），不指向任何数据点：
# plt.text(x, y, s) 三个位置参数的含义：
#   -1  → 文字放置位置的横坐标（数据坐标，即坐标轴上的实际数值）；
#   1   → 文字放置位置的纵坐标（数据坐标）。
#   因为当前 x 轴范围是 [-1, 2]、y 轴范围是 [-2, 3]，
#   所以 (-1, 1) 落在图内左上角附近，文字会显示在那里。
# 第三个参数是文字内容，使用 LaTeX 公式语法（r 前缀表示原始字符串）：
#   This\ is\ a\ test.  → 普通文字 "This is a test."（\ 后接空格表示普通空格）
#   \mu                  → 希腊字母 μ
#   \sigma_i             → 带下标的 σᵢ（下划线 _ 在公式里表示下标）
#   \alpha               → 希腊字母 α
#   最终渲染效果：This is a test. μ σᵢ α
# fontdict={'size':16,'color':'red'}：用字典一次性设置字体属性：
#   size=16    字号 16 磅（等价于单独写 fontsize=16）；
#   color='red' 文字颜色为红色。
# text 与 annotate 的区别：
#   annotate 带箭头，用于"指向"某个数据点做说明；
#   text 不带箭头，只是把文字放在指定坐标处，适合做注释、标题或水印。
# 注意：这行文字同样画在窗口 2 的十字坐标系里（当前窗口仍是窗口 2）。
plt.text(-1,1,r'$This\ is\ a\ test.\ \mu\ \sigma_i\ \alpha$',fontdict={'size':16,'color':'red'})

# ==================== 5.6 批量美化刻度标签（字号 / 白色圆角底框 / 颜色） ====================

# 批量获取当前坐标轴（窗口 2 的十字坐标系）上的所有刻度标签对象：
# ax.get_xticklabels()  返回 x 轴每个刻度对应的 Text 对象列表
#                       （x 轴之前用 xticks 设了 5 个刻度，所以有 5 个标签）；
# ax.get_yticklabels()  返回 y 轴每个刻度对应的 Text 对象列表
#                       （y 轴有 5 个刻度，所以也有 5 个标签）；
# 两个列表用 + 拼接成一个总列表（共 10 个标签），交给 for 循环逐一处理。
# 注意：get_xticklabels() 拿到的是"标签对象"（Text），
# 直接对它调用 set_xxx 方法，就会修改图上对应刻度的显示效果。
for label in ax.get_xticklabels() + ax.get_yticklabels():
    # label.set_fontsize(12)：把当前刻度标签的字体大小设为 12 磅
    # （覆盖之前 xticks/yticks 的默认字号，让数字更醒目、更易读）。
    label.set_fontsize(12)
    # label.set_bbox(dict(...))：给当前刻度标签加一个"底框"（bounding box），
    # 让数字即使压在曲线或网格线上也能清晰可读。参数含义：
    #   facecolor='white'  底框的填充色为白色（相当于给文字垫一张白底）；
    #   edgecolor='none'   底框不画边框线（去掉默认边框，看起来更干净）；
    #   alpha=0.7          底框透明度 0.7（0=全透明，1=不透明）：
    #                      半透明白底既能遮住背后的线条，又不会显得突兀；
    #   boxstyle='round,pad=0.5'  底框形状：round 表示圆角矩形，
    #                       pad=0.5 表示框与文字之间留 0.5 磅的内边距。
    label.set_bbox(dict(facecolor='white', edgecolor='none', alpha=0.7, boxstyle='round,pad=0.5'))
    # label.set_color('blue')：把当前刻度标签的文字颜色设为蓝色。
    # 三个 set_xxx 都是"原地修改"标签对象，不需要返回值。
    label.set_color('blue')

# ==================== 6. 第一次展示 ====================

# 显示到目前为止创建的所有图形窗口（窗口 1 和窗口 2）。
# 程序会阻塞在这里等待用户操作；把所有窗口都关掉后，
# 程序才会继续向下执行。
plt.show()

# ==================== 7. 图例（legend） ====================

# 注意：show() 结束后"当前窗口"仍是窗口 2，
# 所以下面这两条线会继续叠加画在窗口 2 上（该窗口此时已有一条红色抛物线）。
# 这演示了：只要不新建 figure，所有绘图命令都会累积到同一个窗口里。

# plt.plot 的返回值是一个列表（一次 plot 可以画多条线，所以返回 list），
# 这里列表中只有一个 Line2D 线条对象。
# 写法 line1, = ... 是"解包"技巧：等号左边的逗号把列表里的唯一元素取出来
# 赋给 line1（去掉逗号的话 line1 会变成整个列表，传给 legend 会出错）。
# label='up' 是这条线自带的标签；
# 但如果稍后 legend() 里显式给了 labels 参数，这里的 label 会被覆盖。
line1, = plt.plot(x, y1,color='red',linewidth=1.0,linestyle='-',label='up')

# 同理，line2 接收第二条线的 Line2D 对象：
# 灰色虚线画的是 y2 = x^2，自带标签 'down'（同样会被下面的 labels 覆盖）。
line2, = plt.plot(x, y2,color='gray',linewidth=1.0,linestyle='--',label='down')

# 创建图例（legend）：
# handles=[line1, line2]  指定图例要展示哪些线条（这里就是刚画的两条）；
# labels=['aaa', 'bbb']   按顺序与 handles 一一对应，作为图例文字
#                         （覆盖了 plot 时给的 'up'/'down'）；
# loc='best'              让 matplotlib 自动挑选一个与曲线重叠最少的位置放置图例。
# 其他常用 loc 值：'upper right'、'lower left'、'center' 等。
plt.legend(handles=[line1, line2],labels=['aaa', 'bbb'],loc='best')

# 再次弹出窗口展示（此时窗口 2 里共有 3 条曲线 + 1 个图例，窗口 1 保持不变），
# 同样阻塞，直到关闭所有窗口后程序结束。
plt.show()
